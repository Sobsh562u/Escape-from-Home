import random

血条 = 100
天 = 0

print("你被关在家里写作业，想逃出去！")
print("只要撑过 5 天，就是你 18 岁生日，而且你名下有套房，就能逃了。")
print()
print("提示：每天按回车考试。但如果实在忍不了，可以输入 110……")
print("      偷偷告诉你：输入 12345678 可以跳天数。")
print()

while True:
    print("———— 第", 天, "天 ————")
    操作 = input("妈妈发卷子，按回车考试；想报警就输入 110；跳天数输入 12345678：")

    # 作者模式
    if 操作 == "12345678":
        天 = int(input("跳到第几天？（可以填负数！）："))
        continue

    # 报警结局
    if 操作 == "110":
        print()
        print("你拨通了 110……")
        input("警察：你好，请问发生什么事？")
        print("你：我妈家暴我，把我关在家里天天逼我考试！")
        input("警察：你现在的具体位置在哪？")
        print("你：就我家，我把地址发给你们。")
        input("警察：她有没有动手打你？")
        print("你：有！考 0 分就要打我，我血条都快掉光了！")
        input("警察：收到，我们马上出警。")
        print()
        print("==============================")
        print("几分钟后，警车停在你家楼下。")
        print("警察把你妈妈带走了。")
        print("你名下有房，明天 18 岁生日——自由了！")
        print("隐藏结局达成：正义の报警！🚔")
        print("==============================")
        break

    # ===== 负天数彩蛋 =====
    if 天 < 0:
        print()
        if 天 <= -100:
            print("==============================")
            print("你穿越到了", -天, "年前……")
            print("那时候你妈妈都还没出生！")
            print("谁在逼你考试？？？")
            print("你连你自己都还没出生！")
            print()
            print("祖父悖论触发：你穿越回去把自己搞没了，")
            print("那现在的你又是谁？")
            print("结局达成：祖父悖论💥")
            print("==============================")
        else:
            if 操作 == "跑":
                print("你是个受精卵，你居然想跑？！")
                print("你从妈妈肚子里跑出去了……")
                print("没有营养，没有羊水，你直接干死了。")
                print()
                print("结局达成：受精卵体外干死🦠💀")
            else:
                print("你还是个受精卵，在妈妈肚子里。")
                print("没有卷子可以考，也没有血条可以掉。")
                print("结局达成：受精卵体外死亡🦠")
            print("==============================")
        break

    # 撑过5天通关
    if 天 >= 5:
        print()
        print("==============================")
        print("第 5 天结束了！你还活着！")
        print("明天就是你 18 岁生日，你掏出钥匙……")
        print("打开那套写着你名字的房子。")
        print("你终于逃出这个家！结局达成！🏃‍♂️")
        print("==============================")
        break

    # 正常考试
    分数 = random.randint(0, 100)
    print("你这次考了", 分数, "分")

    if 分数 == 0:
        print("妈妈：你怎么考了鸭蛋？！？")
        血条 = 血条 - 40
    elif 分数 < 60:
        print("妈妈：你怎么又考砸了？！")
        血条 = 血条 - 15
    else:
        print("妈妈：这次考得不错，奖励你！")
        血条 = 血条 + 10

    if 血条 > 100:
        血条 = 100
    print("你现在的血条：", 血条, "/ 100")

    if 血条 <= 0:
        print()
        print("你的血条归零……你死了。")
        print("GAME OVER —— 没撑到 18 岁。")
        break

    天 = 天 + 1
    print()
try:
    input("\n按回车键退出...")
except EOFError:
    pass
