# 【扣血规则：分数越低，爸爸下手越狠】
#   0 分  → 扣 100，并且皮带打死，强制结束游戏，血再多也没用
#   10 分 → 扣 90
#   20 分 → 扣 80
#   30 分 → 扣 70
#   40 分 → 扣 60
#   50 分 → 扣 50
#   60 分 → 扣 40
#   70 分 → 扣 30
#   80 分 → 扣 20
#   90 分 → 扣 10
#   100 分 → 不扣血
#   公式就是：扣血 = 100 - 分数

import random

血条 = 100
最大血条 = 100
天 = 0
目标天数 = 5

print("====逃家游戏（极限版）====")
print("爸爸比妈妈还狠，考多少分就扣多少血。")
print("提示：考 0 分，爸爸拿皮带，直接打死，多少血都没用。")
print("提示：想活命，就得考高分。")
print()

while 天 < 目标天数:
    print("———— 第", 天, "天 ————")
    操作 = input("按回车考试 / 跑 / 110 / 12345678：")

    if 操作 == "12345678":
        天 = int(input("跳到第几天："))
        continue

    if 操作 == "110":
        print("你偷偷拨了 110……")
        print("爸爸一把抢过手机：小孩子打什么电话！")
        print("结局达成：报警失败，手机被没收")
        break

    if 操作 == "跑":
        print("你刚打开门，爸爸就在门口抽烟。")
        print("爸爸：往哪跑？")
        血条 = 血条 - 30
        print("血条:", 血条, "/", 最大血条)
        if 血条 <= 0:
            print("结局达成：逃跑未遂，被打趴下")
            break
        天 = 天 + 1
        print()
        continue

    # —— 考试 ——
    分数 = random.randint(0, 100)
    print("你考了", 分数, "分")

    # 0 分：强制结束，无视血条
    if 分数 == 0:
        print()
        print("爸爸：你竟然考零蛋？！")
        print("爸爸解下皮带……")
        print("啪啪啪——")
        print("结局达成：被皮带打死（强制结束，血再多也没用）💀")
        break

    扣血 = 100 - 分数
    if 分数 < 60:
        print("爸爸：这么点分？皮带伺候！")
        print("爸爸抽了你", 扣血, "下，扣", 扣血, "血！")
    else:
        print("爸爸：还算像样，皮带放下了。")
        print("扣", 扣血, "血（分数越高扣得越少）")

    血条 = 血条 - 扣血
    if 血条 < 0:
        血条 = 0
    print("血条:", 血条, "/", 最大血条)

    if 血条 <= 0:
        print()
        print("血条归零，你被打得站不起来。")
        print("结局达成：没撑到 18 岁💀")
        break

    天 = 天 + 1
    print()

if 天 >= 目标天数 and 血条 > 0:
    print("你撑过了 5 天，18 岁生日，名下有房。")
    print("结局达成：极限模式通关🏃‍♂️🏠")

try:
    input("\n按回车键退出...")
except EOFError:
    pass
