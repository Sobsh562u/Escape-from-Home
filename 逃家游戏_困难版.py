import random

血条 = 50
最大血条 = 50
天 = 0
目标天数 = 10          # 要比原版多撑 5 天

print("====逃家游戏（困难版）====")
print("血条只有 50，妈妈更暴躁，要撑 10 天。")
print("提示：考 0 分直接掉一半血；逃跑有风险。")
print()

while 天 < 目标天数:
    print("———— 第", 天, "天 ————")
    操作 = input("按回车考试 / 跑 / 110 / 12345678：")

    if 操作 == "12345678":
        天 = int(input("跳到第几天："))
        continue

    if 操作 == "110":
        print("你拨通了 110……")
        print("警察：小孩子别乱打电话！")
        print("结局达成：被当成恶作剧，没人来救你")
        break

    if 操作 == "跑":
        运气 = random.randint(1, 100)
        if 运气 <= 20:
            print("天没黑你不敢跑，被妈妈抓个正着，扣 10 血！")
            血条 = 血条 - 10
        else:
            print("黑灯瞎火跑出门，又冷又饿，扣 5 血")
            血条 = 血条 - 5
        if 血条 <= 0:
            print("你倒在了楼道里……")
            print("结局达成：逃跑失败")
            break
        print("血条:", 血条, "/", 最大血条)
        天 = 天 + 1
        print()
        continue

    # 考试
    分数 = random.randint(0, 100)
    print("你考了", 分数, "分")

    if 分数 == 0:
        print("妈妈：鸭蛋？！跪墙角！")
        血条 = 血条 - 25
    elif 分数 < 60:
        print("妈妈：又不及格！")
        血条 = 血条 - 15
    elif 分数 < 90:
        print("妈妈：还行，别骄傲。")
        血条 = 血条 + 5
    else:
        print("妈妈：不错。")
        血条 = 血条 + 8

    if 血条 > 最大血条:
        血条 = 最大血条
    print("血条:", 血条, "/", 最大血条)

    if 血条 <= 0:
        print("血条归零，你撑不住了。")
        print("结局达成：倒在第十天之前")
        break

    天 = 天 + 1
    print()

if 天 >= 目标天数 and 血条 > 0:
    print("你撑过了 10 天！18 岁生日，名下有房。")
    print("结局达成：困难模式通关🏃‍♂️🏠")
